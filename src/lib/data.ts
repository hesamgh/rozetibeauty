/** Mixed order for "all" tab — interleaved then shuffled (stable across builds) */
function seededShuffle<T>(items: readonly T[], seed: number): T[] {
  const arr = [...items];
  let state = seed;
  const next = () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 0x100000000;
  };
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(next() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

function mixPortfolioImages() {
  const makeup = PORTFOLIO_IMAGES.filter((img) => img.category === "makeup");
  const nails = PORTFOLIO_IMAGES.filter((img) => img.category === "nails");
  const interleaved: (typeof PORTFOLIO_IMAGES)[number][] = [];
  const maxLen = Math.max(makeup.length, nails.length);
  for (let i = 0; i < maxLen; i++) {
    if (makeup[i]) interleaved.push(makeup[i]);
    if (nails[i]) interleaved.push(nails[i]);
  }
  return seededShuffle(interleaved, 137);
}

